// 거꾸로 나온 카드가 있을 때 덧붙이는 한 줄
export const REV_NOTE = '다만 거꾸로 나온 카드가 있으니, 그 자리에서는 속도를 늦추고 한 번 더 살펴보세요.'

// cards: [{ id, rev }] ×3 (과거·현재·미래) → 해설 문단 (카드 이름은 **굵게** 표시)
export function synthesize(cards) {
  const [p, n, f] = cards.map((c) => SYN[c.id])
  const out = [
    p.p,
    LINK_PN[p.tone + n.tone] + ' ' + lowerFirst(n.n),
    LINK_NF[n.tone + f.tone] + ' ' + lowerFirst(f.f),
    CLOSE[f.tone],
  ]
  if (cards.some((c) => c.rev)) out.push(REV_NOTE)
  return out.join(' ')
}

